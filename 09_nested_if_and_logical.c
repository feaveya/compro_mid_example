#include <stdio.h> // เรียกใช้ไลบรารีสำหรับ printf()

int main(void) // จุดเริ่มต้นของโปรแกรม
{
    int age = 19; // กำหนดอายุตัวอย่าง
    int hasCard = 1; // 1 หมายถึงมีบัตร และ 0 หมายถึงไม่มีบัตร

    if (age >= 18 && hasCard == 1) // && หมายถึงทั้งสองเงื่อนไขต้องเป็นจริง
    {
        printf("Allowed to enter\n"); // แสดงเมื่ออายุถึงและมีบัตร
    }
    else // ทำงานเมื่ออย่างน้อยหนึ่งเงื่อนไขเป็นเท็จ
    {
        printf("Not allowed to enter\n"); // แสดงเมื่ออายุไม่ถึงหรือไม่มีบัตร
    }

    return 0; // จบโปรแกรมอย่างสำเร็จ
}

/* ลองเปลี่ยน age เป็น 17 หรือ hasCard เป็น 0
   && คือ AND, || คือ OR, ! คือ NOT */
