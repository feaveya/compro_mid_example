#include <stdio.h> // เรียกใช้ไลบรารีสำหรับ printf()

int main(void) // จุดเริ่มต้นของโปรแกรม
{
    int i = 1; // กำหนดค่าเริ่มต้นของ i
    int j = 2; // กำหนดค่าเริ่มต้นของ j
    int k; // ประกาศตัวแปร k ไว้เก็บผลคำนวณ

    i++; // เพิ่ม i หลังใช้เป็นคำสั่งเดี่ยว ผลเหมือน ++i
    --j; // ลด j ก่อนใช้เป็นคำสั่งเดี่ยว
    j = i++; // นำค่า i เดิมไปเก็บใน j แล้วจึงเพิ่ม i
    k = ++j + i--; // เพิ่ม j ก่อนบวก แต่นำ i เดิมมาบวกก่อนลด i

    printf("i = %d, j = %d, k = %d\n", i, j, k); // แสดงค่าหลังคำสั่งทั้งหมด

    k = j++ + --i; // นำ j เดิมมาบวกกับ i ที่ลดแล้ว จากนั้นเพิ่ม j
    printf("i = %d, j = %d, k = %d\n", i, j, k); // แสดงค่ารอบที่สอง

    return 0; // จบโปรแกรมอย่างสำเร็จ
}

/* ลำดับที่ได้: บรรทัดแรก i = 2, j = 3, k = 6 และบรรทัดสอง i = 1, j = 4, k = 4
   หลีกเลี่ยงนิพจน์อย่าง i++ + ++i เพราะแก้ค่าตัวแปรเดียวกันมากกว่าหนึ่งครั้งในคำสั่งเดียว */
