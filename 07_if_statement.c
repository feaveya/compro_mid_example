#include <stdio.h> // เรียกใช้ไลบรารีสำหรับ printf()

int main(void) // จุดเริ่มต้นของโปรแกรม
{
    int score = 75; // กำหนดคะแนนตัวอย่าง

    if (score >= 50) // ตรวจว่าคะแนนมากกว่าหรือเท่ากับ 50 หรือไม่
    {
        printf("Pass\n"); // ทำงานเฉพาะเมื่อเงื่อนไขเป็นจริง
    }

    printf("End of program\n"); // ทำงานเสมอ ไม่ว่าเงื่อนไขจะจริงหรือเท็จ

    return 0; // จบโปรแกรมอย่างสำเร็จ
}

/* ลองเปลี่ยน score เป็น 49 แล้วสังเกตว่า Pass จะไม่แสดง
   ใช้ == เพื่อเปรียบเทียบ และใช้ = เพื่อกำหนดค่า */
