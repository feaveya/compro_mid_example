#include <stdio.h> // เรียกใช้ไลบรารีสำหรับ printf()

int main(void) // จุดเริ่มต้นของโปรแกรม
{
    int score = 82; // กำหนดคะแนนตัวอย่าง

    if (score >= 80) // ตรวจเงื่อนไขแรก
    {
        printf("Grade A\n"); // แสดงเมื่อ score ตั้งแต่ 80 ขึ้นไป
    }
    else if (score >= 70) // ตรวจเมื่อเงื่อนไขแรกเป็นเท็จ
    {
        printf("Grade B\n"); // แสดงเมื่อ score อยู่ระหว่าง 70 ถึง 79
    }
    else if (score >= 50) // ตรวจเมื่อเงื่อนไขก่อนหน้าเป็นเท็จ
    {
        printf("Pass\n"); // แสดงเมื่อ score อยู่ระหว่าง 50 ถึง 69
    }
    else // ทำงานเมื่อทุกเงื่อนไขข้างต้นเป็นเท็จ
    {
        printf("Fail\n"); // แสดงเมื่อ score น้อยกว่า 50
    }

    return 0; // จบโปรแกรมอย่างสำเร็จ
}

/* ลองเปลี่ยน score เป็น 75, 50 และ 49
   ควรวางเงื่อนไขคะแนนมากไว้ก่อนคะแนนน้อย เพื่อให้เลือกเกรดถูกต้อง */
