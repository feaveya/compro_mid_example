#include <stdio.h> // เรียกใช้ไลบรารีสำหรับ printf()

int main(void) // จุดเริ่มต้นของโปรแกรม
{
    int result1 = 2 + 3 * 4; // * มีลำดับสูงกว่า + จึงคำนวณ 3 * 4 ก่อน
    int result2 = (2 + 3) * 4; // วงเล็บมีลำดับสูงสุด จึงบวกก่อนคูณ
    int result3 = 20 / 5 + 2 * 3; // คูณและหารก่อนบวก โดยระดับเดียวกันทำซ้ายไปขวา

    printf("2 + 3 * 4 = %d\n", result1); // แสดง 14
    printf("(2 + 3) * 4 = %d\n", result2); // แสดง 20
    printf("20 / 5 + 2 * 3 = %d\n", result3); // แสดง 10

    return 0; // จบโปรแกรมอย่างสำเร็จ
}

/* ลำดับพื้นฐาน: ( ) ก่อน, แล้ว ++/--, ต่อด้วย * / %, และสุดท้าย + -
   ลองเพิ่มวงเล็บใน result3 แล้วเปรียบเทียบผลลัพธ์ */
